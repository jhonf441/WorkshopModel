#!/usr/bin/env node
// Checks every community recipe of recipes/ (CONTRIBUTING-RECIPES.md) with the same judge the plugin uses (dwc-src/recipe-schema.js)
// and, with --write, regenerates the module that bundles them into both DWC lines (dwc-src/community-recipes-data.js and
// dwc36/dwc-src/community-recipes-data.js). Needs Node 22.7 or newer. From the folder of the plugin or the root of the repository:
//
//     node vue/WorkshopModel/tools/check-recipes.js            every file is checked; exit 1 with the problems when one is bad
//     node vue/WorkshopModel/tools/check-recipes.js --write    the same, then the generated module is written for both lines
//     node vue/WorkshopModel/tools/check-recipes.js my.json    one file anywhere (a contributor's draft) is checked
//
// The file name must be <id>.json, ids must be unique and every file must pass validateRecipe().
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { normalizeRecipe, parseRecipeText } from '../dwc-src/recipe-schema.js'

const PLUGIN = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
export const RECIPES_DIR = path.join(PLUGIN, 'recipes')
export const DATA_FILES = [path.join(PLUGIN, 'dwc-src', 'community-recipes-data.js'), path.join(PLUGIN, 'dwc36', 'dwc-src', 'community-recipes-data.js')]

export function problemText(p) {
	return (p.field ? p.field + ': ' : '') + p.code + (p.what ? ' (' + p.what + ')' : '')
}

// -> { recipes: [normalized, by id], problems: ['file: problem'] }
export function checkFolder(dir) {
	const folder = dir || RECIPES_DIR
	const names = readdirSync(folder).filter(n => n.endsWith('.json')).sort()
	const recipes = []
	const problems = []
	const ids = new Map()
	for (const name of names) {
		const { recipe, problems: own } = parseRecipeText(readFileSync(path.join(folder, name), 'utf8'))
		for (const p of own) problems.push(name + ': ' + problemText(p))
		if (!recipe) continue
		if (name !== recipe.id + '.json') problems.push(name + ': the file name must be ' + recipe.id + '.json (the id of the recipe)')
		if (ids.has(recipe.id)) problems.push(name + ': the id ' + recipe.id + ' is already the one of ' + ids.get(recipe.id))
		ids.set(recipe.id, name)
		recipes.push(recipe)
	}
	recipes.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
	return { recipes, problems }
}

// the text of the generated module
export function dataModule(recipes) {
	return "'use strict'\n\n" +
		'// GENERATED by tools/check-recipes.js --write from recipes/*.json (the community recipes, CONTRIBUTING-RECIPES.md): never edit it by\n' +
		'// hand, add or change a JSON file and run the tool. The same file in both DWC lines; test/recipe-schema.test.js fails when it is\n' +
		'// not what the files give. Read by community-recipes.js.\n\n' +
		'export const COMMUNITY_RECIPES = ' + JSON.stringify(recipes.map(normalizeRecipe), null, '\t') + '\n'
}

function main(args) {
	const write = args.indexOf('--write') >= 0
	const files = args.filter(a => !a.startsWith('--'))
	if (files.length) {
		let bad = 0
		for (const f of files) {
			const { problems } = parseRecipeText(readFileSync(f, 'utf8'))
			if (!problems.length) console.log(f + ': OK')
			else {
				bad++
				for (const p of problems) console.log(f + ': ' + problemText(p))
			}
		}
		process.exit(bad ? 1 : 0)
	}
	const { recipes, problems } = checkFolder()
	for (const p of problems) console.log(p)
	if (problems.length) {
		console.log(problems.length + ' problem(s) in ' + RECIPES_DIR)
		process.exit(1)
	}
	console.log(recipes.length + ' recipe(s) OK: ' + recipes.map(r => r.id).join(', '))
	if (write) {
		const text = dataModule(recipes)
		for (const f of DATA_FILES) {
			writeFileSync(f, text)
			console.log('written ' + f)
		}
	} else {
		const text = dataModule(recipes)
		for (const f of DATA_FILES) {
			let current = ''
			try {
				current = readFileSync(f, 'utf8')
			} catch (e) {
				current = ''
			}
			if (current !== text) {
				console.log(f + ' is out of date: run the tool with --write')
				process.exit(1)
			}
		}
	}
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2))
